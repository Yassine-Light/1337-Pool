#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	prn[12];
	int		i;

	i = 0;
	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = nb * -1;
	}
	if (nb == 0)
		prn[i++] = '0';
	while (nb > 0)
	{
		prn[i++] = nb % 10 + '0';
		nb = nb / 10;
	}
	while (i > 0)
		write(1, &prn[--i], 1);
}
